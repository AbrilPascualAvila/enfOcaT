<?php
    $num1 = 10;
    $num2 = 5;

    // Suma con asignación
    $num1 += $num2; 
    echo "Después de la suma, num1 es: $num1\n";

    // Resta con asignación
    $num1 -= $num2; 
    echo "Después de la resta, num1 es: $num1\n";

    // Multiplicación con asignación
    $num1 *= $num2; 
    echo "Después de la multiplicación, num1 es: $num1\n";

    // División con asignación
    $num1 /= $num2; 
    echo "Después de la división, num1 es: $num1\n";

    // Módulo con asignación
    $num1 %= $num2; 
    echo "Después del módulo, num1 es: $num1\n";
?>
